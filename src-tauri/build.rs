/// Generate the Web Reader's PDF.js static asset table.
///
/// The LAN reader cannot read the desktop `dist/` at runtime, so the exact
/// `pdf.min.mjs` / `pdf.worker.min.mjs` and the two data directories PDF.js
/// needs (CMaps and standard 14 fonts) are embedded at compile time from the
/// same `pdfjs-dist` package the desktop build uses. WASM modules and the
/// quickjs document-script sandbox are intentionally absent: they would either
/// require relaxing the reader CSP or allow PDF JavaScript to run.
fn generate_pdf_assets() {
    use std::fmt::Write as _;
    use std::path::{Path, PathBuf};

    let manifest_dir = PathBuf::from(
        std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set for build scripts"),
    );
    let out_dir =
        PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR is set for build scripts"));
    let package_root = manifest_dir
        .join("..")
        .join("node_modules")
        .join("pdfjs-dist");
    let target = out_dir.join("pdf_assets.rs");

    let mut entries: Vec<(String, String, &'static str)> = Vec::new();
    let mut push = |name: String, relative: String, mime: &'static str| {
        let absolute = manifest_dir
            .join("..")
            .join("node_modules")
            .join("pdfjs-dist")
            .join(&relative);
        assert!(
            absolute.is_file(),
            "missing PDF.js web-reader asset {}; run `npm ci` before building the Rust backend",
            absolute.display()
        );
        println!("cargo:rerun-if-changed={}", absolute.display());
        entries.push((name, relative.replace('\\', "/"), mime));
    };

    push(
        "pdf.min.mjs".to_owned(),
        "legacy/build/pdf.min.mjs".to_owned(),
        "text/javascript; charset=utf-8",
    );
    push(
        "pdf.worker.min.mjs".to_owned(),
        "legacy/build/pdf.worker.min.mjs".to_owned(),
        "text/javascript; charset=utf-8",
    );

    for (directory, extensions) in [
        ("cmaps", &["bcmap"][..]),
        ("standard_fonts", &["pfb", "ttf"][..]),
    ] {
        let root = package_root.join(directory);
        println!("cargo:rerun-if-changed={}", root.display());
        let mut files = std::fs::read_dir(&root)
            .unwrap_or_else(|error| {
                panic!(
                    "cannot read PDF.js web-reader assets from {}: {error}; run `npm ci` first",
                    root.display()
                )
            })
            .filter_map(|entry| entry.ok())
            .filter(|entry| entry.file_type().is_ok_and(|kind| kind.is_file()))
            .filter(|entry| {
                Path::new(&entry.file_name())
                    .extension()
                    .and_then(|extension| extension.to_str())
                    .is_some_and(|extension| extensions.contains(&extension))
            })
            .map(|entry| entry.file_name().to_string_lossy().into_owned())
            .collect::<Vec<_>>();
        files.sort();
        for file in files {
            let mime = if file.ends_with(".ttf") {
                "font/ttf"
            } else {
                "application/octet-stream"
            };
            push(
                format!("{directory}/{file}"),
                format!("{directory}/{file}"),
                mime,
            );
        }
    }

    let mut generated = String::from(
        "// @generated by build.rs from node_modules/pdfjs-dist. Do not edit.\n\
         pub(crate) static PDF_ASSETS: &[(&str, &[u8], &str)] = &[\n",
    );
    for (name, relative, mime) in &entries {
        writeln!(
            generated,
            "    (\"{name}\", include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/../node_modules/pdfjs-dist/{relative}\")), \"{mime}\"),"
        )
        .expect("write generated PDF asset entry");
    }
    generated.push_str("];\n");
    std::fs::write(&target, generated).expect("write generated PDF asset table");
}

fn main() {
    generate_pdf_assets();
    // Expose a stable, human-readable build baseline to the updater UI.
    // This is intentionally a build-time value: release builds from a dirty
    // tree should not claim a clean commit.
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default();
    let commit = std::process::Command::new("git")
        .args(["rev-parse", "--short=12", "HEAD"])
        .current_dir(&manifest_dir)
        .output()
        .ok()
        .filter(|output| output.status.success())
        .and_then(|output| String::from_utf8(output.stdout).ok())
        .map(|text| text.trim().to_string())
        .filter(|text| !text.is_empty())
        .unwrap_or_else(|| "local".to_string());
    let dirty = std::process::Command::new("git")
        .args(["status", "--porcelain", "--untracked-files=no"])
        .current_dir(&manifest_dir)
        .output()
        .ok()
        .filter(|output| output.status.success())
        .map(|output| !output.stdout.is_empty())
        .unwrap_or(true);
    let baseline = if dirty {
        format!("{commit}-dirty")
    } else {
        commit
    };
    println!("cargo:rustc-env=MR_BUILD_BASELINE={baseline}");
    println!("cargo:rerun-if-changed=build.rs");
    // 版本基线跟随工作区：HEAD/分支、暂存区、前后端源码与清单任一变化
    // 都重跑构建脚本，避免后端显示 clean 而前端显示 -dirty 的漂移。
    println!("cargo:rerun-if-changed=../.git/HEAD");
    println!("cargo:rerun-if-changed=../.git/index");
    println!("cargo:rerun-if-changed=../.git/refs/heads");
    println!("cargo:rerun-if-changed=src");
    println!("cargo:rerun-if-changed=../src");
    println!("cargo:rerun-if-changed=../package.json");
    println!("cargo:rerun-if-changed=../package-lock.json");
    println!("cargo:rerun-if-changed=Cargo.toml");
    tauri_build::build()
}
